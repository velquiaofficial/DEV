def style_header(ws, n):
    for c in range(1, n + 1):
        cell = ws.cell(1, c)
        cell.fill = HEADER_FILL
        cell.font = HEADER_FONT
        cell.alignment = Alignment(wrap_text=True, vertical="center", horizontal="center")
        cell.border = THIN
    ws.row_dimensions[1].height = 32
    ws.freeze_panes = "A2"
    ws.auto_filter.ref = f"A1:{get_column_letter(n)}1"


def autosize(ws, max_w=48):
    for col in ws.columns:
        letter = get_column_letter(col[0].column)
        width = 12
        for cell in col[:60]:
            if cell.value:
                width = max(width, min(max_w, len(str(cell.value)) + 2))
        ws.column_dimensions[letter].width = width


def write_table(ws, headers, rows):
    for j, h in enumerate(headers, 1):
        ws.cell(1, j, h)
    style_header(ws, len(headers))
    for i, row in enumerate(rows, 2):
        for j, val in enumerate(row, 1):
            cell = ws.cell(i, j, val)
            cell.border = THIN
            cell.alignment = Alignment(wrap_text=True, vertical="top")
            if i % 2 == 0:
                cell.fill = ZEBRA
        ws.row_dimensions[i].height = max(36, 18 * (1 + max(str(x).count("\n") for x in row)))
    autosize(ws)


