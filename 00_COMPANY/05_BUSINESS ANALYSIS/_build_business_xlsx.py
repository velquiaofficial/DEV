def sheet_per_biz(wb):
    by = {}
    for row in PLAYBOOKS:
        by.setdefault(row[0], []).append(row)
    names = {r[0]: r[1] for r in OVERVIEW}
    for bid, rows in by.items():
        ws = wb.create_sheet(SHEET_ALIAS.get(bid, bid))
        headers = [
            "phase", "phase_name", "step_no", "やること", "具体アクション", "成果物",
            "目安期間", "目安コスト", "使う道具/サービス", "KPI", "よくある失敗",
        ]
        slim = [r[2:] for r in rows]
        write_table(ws, headers, slim)
        ws.insert_rows(1)
        ws["A1"] = f"{bid} {names[bid]} — 進め方"
        ws["A1"].font = TITLE
        ws.merge_cells("A1:K1")
        ws["A1"].fill = ACCENT
        ws.freeze_panes = "A3"


