    sheet_per_biz(wb)

    xlsx = OUT / f"VELQUIA_Business_Analysis_{AS_OF}.xlsx"
    wb.save(xlsx)

    # CSVs
    def dump(name, headers, rows):
        path = OUT / name
        with path.open("w", newline="", encoding="utf-8-sig") as f:
            w = csv.writer(f)
            w.writerow(headers)
            w.writerows(rows)
        print("csv", path.name)

    dump("01_overview.csv", OVERVIEW_H, OVERVIEW)
    dump("02_playbook_all.csv", STEP_H, PLAYBOOKS)
