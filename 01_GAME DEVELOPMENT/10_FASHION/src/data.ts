export function categoryLabel(product: Product): string {
  if (product.kind === "fashion" && product.fashionCategory) {
    return LABELS[product.fashionCategory] ?? "服";
  }
  if (product.kind === "beauty" && product.beautyCategory) {
    return LABELS[product.beautyCategory] ?? "コスメ";
  }
  return product.kind === "fashion" ? "服" : "コスメ";
}

