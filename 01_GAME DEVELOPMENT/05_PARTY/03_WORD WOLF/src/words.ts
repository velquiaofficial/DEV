function toPair(row: Row): WordPair {
  const [id, category, difficulty, citizen, citizenRead, wolf, wolfRead] = row;
  return { id, category, difficulty, citizen, citizenRead, wolf, wolfRead };
}

export const PAIRS: WordPair[] = ROWS.map(toPair);

export function categoryList(custom: WordPair[] = []): string[] {
  const seen: string[] = [];
  for (const pair of [...PAIRS, ...custom]) {
    if (!seen.includes(pair.category)) seen.push(pair.category);
  }
  return seen;
}
